const assert = require('node:assert/strict');
const { createMediaAccess } = require('../src/native/media-access');
const media = createMediaAccess('http://localhost:5173');
const file = require('node:path').resolve('sample.mp4');
const url = media.localUrl(file);
assert.equal(media.localUrl(file), url);
assert.equal(media.resolveLocal(url), file);
assert.equal(media.resolveLocal('hongguo-local://f/' + Buffer.from(file).toString('base64url')), null);
assert.equal(media.resolveLocal(url + '?path=other'), null);
assert.equal(media.resolveLocal(url.replace('://f/', '://other/')), null);
const request = (origin, initiatorOrigin = origin) => ({ headers: new Headers(origin ? { Origin: origin } : {}), initiatorOrigin });
assert.equal(media.corsHeaders(request('null'))['Access-Control-Allow-Origin'], 'null');
assert.equal(media.corsHeaders(request('http://localhost:5173'))['Access-Control-Allow-Origin'], 'http://localhost:5173');
assert.equal(media.corsHeaders(request('https://untrusted.example')), null);
assert.equal(media.corsHeaders(request('null', 'https://untrusted.example')), null);
assert.equal(media.corsHeaders(request('http://localhost:5173', 'null')), null);
media.clear(); assert.equal(media.resolveLocal(url), null);
console.log('PASS media access: stable opaque capability, no path fallback, origin checks, cleanup');
